def ast_dossiers(path: Path, source: str) -> list[str]:
    if path.suffix != ".py":
        return []
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []
    result = ["### Досье классов и функций", ""]
    for node in ast.walk(tree):
        if not isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        if isinstance(node, ast.ClassDef):
            kind = "Класс"
            args = ", ".join(ast.unparse(base) for base in node.bases) or "без явного родителя"
            purpose = CLASS_PURPOSES.get(node.name, "Группирует связанные данные и поведение.")
        else:
            kind = "Функция"
            args = ", ".join(arg.arg for arg in node.args.args) or "без параметров"
            purpose = VIEW_PURPOSES.get(node.name, "Выполняет локальную операцию, названную в идентификаторе функции.")
        end = getattr(node, "end_lineno", node.lineno)
        decorators = []
        if hasattr(node, "decorator_list"):
            decorators = [ast.unparse(item) for item in node.decorator_list]
        segment = ast.get_source_segment(source, node) or ""
        models = sorted(set(re.findall(
            r"\b(Profile|Doctor|DoctorWorkplace|MedicalService|WorkSchedule|Appointment|AppointmentImage|AppointmentVideo|DoctorPatientCard|PatientRecordEntry|PatientRecordImage|PatientRecordVideo|AuditLog|TelegramConnection|TelegramLinkToken|TelegramNotification|ClinicSettings|HomeHeroSlide|NewsPost|GalleryImage)\b",
            segment,
        )))
        templates = sorted(set(re.findall(r"['\"]clinic/([^'\"]+\.html)['\"]", segment)))
        result.extend([
            f"#### {kind} `{node.name}`",
            "",
            f"- Расположение: `{relative(path)}:{node.lineno}`, заканчивается около строки {end}.",
            f"- Параметры или родители: `{text_cell(args)}`.",
            f"- Назначение: {purpose}",
            f"- Декораторы: {', '.join(f'`{item}`' for item in decorators) if decorators else 'нет'}.",
            f"- Модели в этом фрагменте: {', '.join(f'`{item}`' for item in models) if models else 'прямо не упоминаются'}.",
            f"- HTML-шаблоны: {', '.join(f'`{item}`' for item in templates) if templates else 'не возвращает шаблон напрямую'}.",
            "",
        ])
    return result


def button_index() -> list[str]:
    rows = [
        "# Индекс кнопок и ссылок: от надписи до backend",
        "",
        "Ниже перечислены интерактивные элементы шаблонов. Для многострочных кнопок берется видимый текст после удаления HTML и команд шаблона. Если цель является Django URL, указано имя маршрута, по которому можно найти view в `clinic/urls.py`.",
        "",
        "| Шаблон | Видимая надпись | Маршрут или действие | Что происходит на уровне кода |",
        "|---|---|---|---|",
    ]
    tag_pattern = re.compile(r"<(a|button|summary)\b([^>]*)>(.*?)</\1>", re.I | re.S)
    for path in sorted((ROOT / "templates/clinic").glob("*.html")):
        source = path.read_text(encoding="utf-8")
        for match in tag_pattern.finditer(source):
            tag, attrs, body = match.groups()
            label = re.sub(r"{%.*?%}|{{.*?}}|<[^>]+>", " ", body, flags=re.S)
            label = " ".join(label.split())
            if not label:
                label = "динамическая надпись или иконка"
            route_match = re.search(r"{%\s*url\s+['\"]([^'\"]+)", attrs)
            form_start = source.rfind("<form", 0, match.start())
            previous_form_end = source.rfind("</form>", 0, match.start())
            form_end = source.find("</form>", match.end())
            form_source = ""
            if form_start > previous_form_end and form_end >= 0:
                form_source = source[form_start:form_end]
            action_match = re.search(
                r'name=["\']action["\']\s+value=["\']([^"\']+)',
                form_source,
            )
            target = f"URL `{route_match.group(1)}`" if route_match else (
                f"POST action `{action_match.group(1)}`" if action_match else "текущая форма или JavaScript"
            )
            if tag.casefold() == "a":
                behavior = "Браузер делает GET по адресу; Django URL resolver выбирает связанную view."
            elif "type=\"submit\"" in attrs or "type='submit'" in attrs or "type=" not in attrs:
                behavior = "Браузер отправляет ближайшую форму; view повторно проверяет данные и права."
            else:
                behavior = "JavaScript обрабатывает кнопку без непосредственного изменения базы."
            rows.append(
                f"| `{relative(path)}` | {text_cell(label)} | {target} | {behavior} |"
            )
    rows.append("")
    return rows


