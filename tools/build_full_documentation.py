def python_contexts(source: str) -> dict[int, str]:
    contexts: dict[int, tuple[int, str]] = {}
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return {}

    def walk(node: ast.AST, parents: list[str]) -> None:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            qualified = ".".join([*parents, node.name])
            start = getattr(node, "lineno", 1)
            end = getattr(node, "end_lineno", start)
            depth = len(parents) + 1
            for number in range(start, end + 1):
                previous = contexts.get(number)
                if previous is None or depth >= previous[0]:
                    contexts[number] = (depth, qualified)
            parents = [*parents, node.name]
        for child in ast.iter_child_nodes(node):
            walk(child, parents)

    walk(tree, [])
    return {number: value[1] for number, value in contexts.items()}


